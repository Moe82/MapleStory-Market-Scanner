CREATE TABLE items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maplestory_id INTEGER NOT NULL,
    name TEXT NOT NULL,
    category TEXT,
    subcategory TEXT,
    description TEXT,
    icon_path TEXT,
    metadata JSONB,
    region TEXT,
    version TEXT,

    last_synced_at TIMESTAMPTZ,

    CONSTRAINT unique_maplestory_item
        UNIQUE (maplestory_id, region, version)
);
